//go:build ignore

// gen_zones writes zones_gen.go: the time zone names in the Go toolchain's
// time zone database (lib/time/zoneinfo.zip, the same data the time/tzdata
// package builds into the binary). After upgrading Go, run:
//
//	go generate ./internal/tzdb
//
// TestZoneListMatchesGo fails when the list is out of date.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
)

// excluded are names in the database that are not real time zones.
var excluded = map[string]bool{
	"Factory": true, // placeholder meaning "time zone unknown"
}

func main() {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatalf("go env GOROOT: %v", err)
	}
	path := filepath.Join(strings.TrimSpace(string(out)), "lib", "time", "zoneinfo.zip")
	zr, err := zip.OpenReader(path)
	if err != nil {
		log.Fatal(err)
	}
	defer zr.Close()

	var names []string
	for _, f := range zr.File {
		if !f.FileInfo().IsDir() && !excluded[f.Name] {
			names = append(names, f.Name)
		}
	}
	slices.Sort(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_zones.go from the time zone database of %s; DO NOT EDIT.\n\n", runtime.Version())
	b.WriteString("package tzdb\n\n// allZones lists the valid time zone names, sorted.\nvar allZones = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zones_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("zones_gen.go: %d zones\n", len(names))
}
